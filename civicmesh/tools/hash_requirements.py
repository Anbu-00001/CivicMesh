"""Write requirements.hashes.txt: every pinned package with PyPI's sha256 for each of its files.

    python3 civicmesh/tools/hash_requirements.py          # write
    python3 civicmesh/tools/hash_requirements.py --check  # fail if a pin has no hashes

The image installs with --require-hashes, so a replaced file on PyPI stops the
build. requirements.txt stays the human-edited list. Stdlib only.
"""
import json
import os
import re
import sys
import urllib.request

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
SRC = os.path.join(ROOT, "requirements.txt")
OUT = os.path.join(ROOT, "requirements.hashes.txt")


def pins():
    out = []
    for line in open(SRC, encoding="utf-8"):
        line = line.split("#")[0].strip()
        if line:
            m = re.fullmatch(r"([A-Za-z0-9_.\-\[\],]+)==([^\s;]+)", line)
            if not m:
                sys.exit(f"not an exact pin: {line}")
            out.append((m.group(1), m.group(2)))
    return out


def main():
    if "--check" in sys.argv:
        have = open(OUT, encoding="utf-8").read()
        missing = [f"{n}=={v}" for n, v in pins() if f"{n}=={v} " not in have]
        if missing:
            sys.exit(f"requirements.hashes.txt is out of date: {missing}")
        print(f"requirements.hashes.txt covers {len(pins())} pins")
        return
    lines = ["# Generated by civicmesh/tools/hash_requirements.py from requirements.txt. Don't edit by hand.\n"]
    for name, ver in pins():
        base = name.split("[")[0]
        req = urllib.request.Request(f"https://pypi.org/pypi/{base}/{ver}/json", headers={"User-Agent": "civicmesh-hash-tool"})
        files = json.load(urllib.request.urlopen(req, timeout=30))["urls"]
        hashes = sorted({f["digests"]["sha256"] for f in files})
        if not hashes:
            sys.exit(f"no files for {name}=={ver}")
        lines.append(f"{name}=={ver} " + " ".join(f"--hash=sha256:{h}" for h in hashes) + "\n")
    with open(OUT, "w", encoding="utf-8") as f:
        f.writelines(lines)
    print(f"wrote {len(lines) - 1} pins")


if __name__ == "__main__":
    main()
